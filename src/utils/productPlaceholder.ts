/**
 * Определяет цвета градиента по названию продукта.
 */
export function getPlaceholderColors(productName: string): [string, string] {
  const lower = productName.toLowerCase();
  let bestLen = 0;
  let bestColors: [string, string] = ['#2C3E50', '#4A6741']; // default

  for (const [keyword, colors] of KEYWORD_COLORS) {
    if (lower.includes(keyword) && keyword.length > bestLen) {
      bestLen = keyword.length;
      bestColors = colors;
    }
  }
  return bestColors;
}

/**
 * Генерирует data:image/svg+xml placeholder.
 * Градиентный фон + первая буква по центру.
 * Размер можно передать (по умолчанию 300×200).
 */
export function createSvgPlaceholder(
  productName: string,
  width = 300,
  height = 200,
): string {
  const letter = productName.trim().charAt(0).toUpperCase() || '?';
  const [c1, c2] = getPlaceholderColors(productName);
  const fontSize = Math.min(width, height) * 0.4;
  const y = height / 2 + fontSize * 0.35;

  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}"><defs><linearGradient id="g" x1="0%" y1="0%" x2="100%" y2="100%"><stop offset="0%" stop-color="${c1}"/><stop offset="100%" stop-color="${c2}"/></linearGradient></defs><rect width="${width}" height="${height}" fill="url(#g)"/><text x="${width / 2}" y="${y}" font-family="Georgia,serif" font-size="${fontSize}" fill="rgba(255,255,255,0.35)" text-anchor="middle" font-weight="bold">${letter}</text></svg>`;

  return `data:image/svg+xml,${encodeURIComponent(svg)}`;
}

/**
 * Возвращает первую букву (для inline React компонента).
 */
export function getPlaceholderLetter(productName: string): string {
  return productName.trim().charAt(0).toUpperCase() || '?';
}
