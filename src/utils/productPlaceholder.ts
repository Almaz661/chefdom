/**
 * Определяет цвет фона placeholder по названию продукта.
 * Ищет ключевые слова в названии (регистронезависимо).
 */
export function getPlaceholderColor(productName: string): string {
  const lower = productName.toLowerCase();

  // Ищем самое длинное совпадение (более специфичное)
  let bestKey = '';
  let bestColor = '#6b7280'; // серый по умолчанию

  for (const [keyword, color] of Object.entries(CATEGORY_COLORS)) {
    if (lower.includes(keyword) && keyword.length > bestKey.length) {
      bestKey = keyword;
      bestColor = color;
    }
  }

  return bestColor;
}

/**
 * Возвращает первую букву названия (для placeholder).
 */
export function getPlaceholderLetter(productName: string): string {
  return productName.trim().charAt(0).toUpperCase() || '?';
}
