// Нормализация категории рецепта.
//
// Проблема: category хранится свободным текстом. Из-за этого «Десерты»,
// «Десерт» и «десерт» (разный регистр и единственное/множественное число)
// попадают в БД как РАЗНЫЕ категории и в списке рецептов дробятся на
// отдельные чипы с раздельными счётчиками.
//
// Решение: единый нормализатор. Он приводит вход к каноничной метке.
//   1. Известные синонимы (ед./мн. число) → каноничная форма из словаря.
//   2. Всё остальное → Trim + первая буква заглавная, остальные строчные
//      (чтобы хотя бы регистровые варианты «соус»/«Соус» слились).
//
// Используется на ВСЕХ путях записи (ручное создание/редактирование,
// импорт с сайта, импорт с YouTube) и при агрегации getCategories.

// Каноничные метки — во множественном числе, с заглавной буквы.
// Ключ словаря — вход в нижнем регистре (после trim).
const CATEGORY_ALIASES: Record<string, string> = {
  // Десерты
  десерт: 'Десерты',
  десерты: 'Десерты',
  сладкое: 'Десерты',
  сладости: 'Десерты',
  // Основные блюда
  'основное блюдо': 'Основные блюда',
  'основные блюда': 'Основные блюда',
  основные: 'Основные блюда',
  основное: 'Основные блюда',
  горячее: 'Основные блюда',
  'второе блюдо': 'Основные блюда',
  второе: 'Основные блюда',
  // Салаты
  салат: 'Салаты',
  салаты: 'Салаты',
  // Супы
  суп: 'Супы',
  супы: 'Супы',
  // Закуски
  закуска: 'Закуски',
  закуски: 'Закуски',
  // Завтраки
  завтрак: 'Завтраки',
  завтраки: 'Завтраки',
  // Соусы
  соус: 'Соусы',
  соусы: 'Соусы',
  // Выпечка
  выпечка: 'Выпечка',
  // Напитки
  напиток: 'Напитки',
  напитки: 'Напитки',
  // Заготовки
  заготовка: 'Заготовки',
  заготовки: 'Заготовки',
};

export function normalizeRecipeCategory(
  raw: string | null | undefined,
): string | null {
  if (raw == null) return null;
  const trimmed = String(raw).trim();
  if (!trimmed) return null;

  const key = trimmed.toLowerCase();
  if (CATEGORY_ALIASES[key]) return CATEGORY_ALIASES[key];

  // Fallback: нормализуем регистр, чтобы «соус»/«Соус»/«СОУС» слились.
  return trimmed.charAt(0).toUpperCase() + trimmed.slice(1).toLowerCase();
}
